        actualBoardStep4.Should().Be(expectedBoard);

        // 5 step
        _game.Iterate();
        var actualBoardStep5 = _board.ToString();

        actualBoardStep5.Should().Be(expectedBoard);
    }


    private string GetFilePath(string fileName)
    {
        var filePath = Path.Combine(_testDirectory, fileName + ".txt");
        Assert.That(File.Exists(filePath), Is.True, "Файл не найден в директории сборки.");

        return filePath;
    }
