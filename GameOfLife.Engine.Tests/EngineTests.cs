";
        var filePath = GetFilePath(nameof(Test2_Stability));

        // Act
        _game.InitializeGame(filePath);

        // 1 step
        _game.Iterate();
        var actualBoardStep1 = _board.ToString();

        actualBoardStep1.Should().Be(expectedBoard);

        // 2 step
        _game.Iterate();
        var actualBoardStep2 = _board.ToString();

        actualBoardStep2.Should().Be(expectedBoard);

